  it("invariant fuzz: per-rental escrow conservation and single occupancy", async () => {
    const escrowIn = new Map<string, number>();
    const open = new Set<string>();

    for (let i = 0; i < 20; i += 1) {
      const useL1 = i % 2 === 0;
      const listing = useL1 ? l1 : l2;
      const owner = useL1 ? ownerA : ownerB;
      const listingKey = listing.toBase58();

      const l = await program.account.assetListing.fetch(listing);
      if (!l.currentRental.equals(PublicKey.default)) {
        // Listing busy: exercise a terminal transition deterministically.
        const rental: PublicKey = l.currentRental;
        const r = await program.account.rentalAgreement.fetch(rental);
        const code = statusCode(r.status);
        if (code === RENTAL_STATUS.Reserved || code === RENTAL_STATUS.Active) {
          if (i % 4 === 1) {
            await raiseDispute(program, { party: owner.publicKey, listing, rental, signers: [owner] });
            await resolveDispute(program, {
              admin: admin.publicKey,
              listing,
              rental,
              ownerWallet: owner.publicKey,
              renterWallet: renter.publicKey,
              ownerShareBps: 7_500,
              signers: [admin],
            });
            open.delete(rental.toBase58());
          } else {
            await cancelRental(program, {
              party: renter.publicKey,
              listing,
              rental,
              renterWallet: renter.publicKey,
              signers: [renter],
            });
            open.delete(rental.toBase58());
          }
          // Reclaim this rental's rent before the next fuzz iteration; the
          // 20-iteration loop would otherwise exhaust a 0.05 SOL renter.
          await closeRental(program, { rental, renterWallet: renter.publicKey });
          trackedRentals.delete(rental.toBase58());
        }
        continue;
      }

      const rentalId = newRentalId();
      const [rental] = rentalPda(listing, rentalId);
      const days = 1 + (i % 3);
      const start = nowTs() + 3_600;
      await createRental(program, {
        renter: renter.publicKey,
        listing,
        rentalId,
        startTs: start,
        days,
        signers: [renter],
      });
      const r = await program.account.rentalAgreement.fetch(rental);
      escrowIn.set(rental.toBase58(), r.escrowLamports.toNumber());
      assert.ok(!open.has(listingKey), "two open rentals must never share a listing");
      open.add(listingKey);

      const before = await balance(rental);
      await cancelRental(program, {
        party: renter.publicKey,
        listing,
        rental,
        renterWallet: renter.publicKey,
        signers: [renter],
      });
      const refunded = before - (await balance(rental));
      assert.equal(refunded, escrowIn.get(rental.toBase58()));
      open.delete(listingKey);

      // Reclaim rent immediately so the next iteration reuses the same 0.05 SOL.
      await closeRental(program, { rental, renterWallet: renter.publicKey });
      trackedRentals.delete(rental.toBase58());
    }

    assert.equal(open.size, 0, "every rental reached a terminal state");
  });
