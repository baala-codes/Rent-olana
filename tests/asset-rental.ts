const nowTs = (): number => Math.floor(Date.now() / 1000);

const waitFinalized = async (signature: TransactionSignature): Promise<void> => {
  const latest = await connection.getLatestBlockhash("finalized");
  await connection.confirmTransaction({ signature, ...latest }, "finalized");
};

const feeOf = async (signature: TransactionSignature): Promise<number> => {
  const tx = await connection.getTransaction(signature, {
    commitment: "finalized",
    maxSupportedTransactionVersion: 0,
  });
  return tx?.meta?.fee ?? 0;
};

const balance = (pubkey: PublicKey): Promise<number> =>
  connection.getBalance(pubkey, "finalized");

async function fund(to: PublicKey, sol = 5): Promise<void> {
  const tx = new anchor.web3.Transaction().add(
    SystemProgram.transfer({
      fromPubkey: admin.publicKey,
      toPubkey: to,
      lamports: sol * LAMPORTS_PER_SOL,
    })
  );
  await provider.sendAndConfirm(tx, [admin]);
}

type Snap = { address: string; exists: boolean; lamports: number };

async function snapshot(accounts: Record<string, PublicKey>): Promise<Record<string, Snap>> {
  const entries = Object.entries(accounts);
  const infos = await connection.getMultipleAccountsInfo(
    entries.map(([, pk]) => pk),
    "finalized"
  );
  const out: Record<string, Snap> = {};
  entries.forEach(([name, pk], i) => {
    out[name] = {
      address: pk.toBase58(),
      exists: infos[i] !== null,
      lamports: infos[i]?.lamports ?? 0,
    };
  });
  return out;
}

/** Run a case, capture a pre/post snapshot of `tracked`, and dump a fixture. */
async function scenario(
  name: string,
  tracked: Record<string, PublicKey>,
  fn: () => Promise<TransactionSignature | null>
): Promise<void> {
  const before = await snapshot(tracked);
  let signature: TransactionSignature | null = null;
  try {
    signature = await fn();
    if (signature) await waitFinalized(signature);
  } finally {
    const after = await snapshot(tracked);
    const accounts: Record<string, unknown> = {};
    for (const key of Object.keys(tracked)) {
      accounts[key] = {
        address: before[key].address,
        exists: after[key].exists,
        before: before[key],
        after: after[key],
      };
    }
    mkdirSync(FIXTURES, { recursive: true });
    writeFileSync(
      join(FIXTURES, `${name}.json`),
      JSON.stringify(
        {
          scenario: name,
          cluster: CLUSTER,
          programId: PROGRAM_ID.toBase58(),
          signature,
          accounts,
          capturedAt: new Date().toISOString(),
        },
        null,
        2
      ) + "\n"
    );
  }
}

const codeOf = (err: unknown): number | undefined => {
  const e = err as any;
  return e?.error?.errorCode?.number ?? e?.error?.errorCode?.code ?? e?.errorCode?.number;
};

async function expectError(fn: () => Promise<unknown>, name: keyof typeof RENTAL_ERROR_CODE): Promise<void> {
  const expected = RENTAL_ERROR_CODE[name as string];
  try {
    await fn();
  } catch (err) {
    const code = codeOf(err);
    assert.equal(code, expected, `expected ${String(name)} (${expected}), got ${code}`);
    return;
  }
  assert.fail(`expected ${String(name)}, but the call succeeded`);
}

async function expectFailure(fn: () => Promise<unknown>): Promise<void> {
  try {
    await fn();
  } catch {
    return;
  }
  assert.fail("expected the call to fail");
}

