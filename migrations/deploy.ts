// Anchor runs this once after `anchor deploy`.
//
// The only post-deploy step is creating the singleton `PlatformConfig` (PDA
// `[b"config"]`) signed by the admin wallet. `initialize_config` can run only
// once, so this is idempotent: if the config account already exists we leave it
// untouched and log the current values instead of failing the deploy.
//
// Configure the treasury and fee with environment variables, or edit the
// defaults below:
//
//   TREASURY  base58 treasury pubkey (receives the platform fee)
//   FEE_BPS   fee in basis points, capped on-chain at MAX_FEE_BPS (1000 = 10%)

import * as anchor from "@coral-xyz/anchor";
import { Program } from "@coral-xyz/anchor";
import { PublicKey } from "@solana/web3.js";
import { join } from "path";

const DEFAULT_TREASURY = "23Y75gsoeTF68uMxPVZ6TtMfL6a73bDouxLJLRZ6kTeX";
const DEFAULT_FEE_BPS = 250;

module.exports = async function (provider: anchor.AnchorProvider) {
  anchor.setProvider(provider);
  // Loosely typed: the IDL is generated by `anchor build`, so the migration
  // must compile before `target/idl/asset_rental.json` exists.
  // eslint-disable-next-line @typescript-eslint/no-explicit-any
  const program: any = new Program(
    require(join(__dirname, "..", "target", "idl", "asset_rental.json")),
    provider
  );

  const [config] = PublicKey.findProgramAddressSync(
    [Buffer.from("config")],
    program.programId
  );

  const existing = await program.provider.connection.getAccountInfo(config);
  if (existing) {
    const decoded = await program.account.platformConfig.fetch(config);
    console.log("PlatformConfig already initialized:", {
      admin: decoded.admin.toBase58(),
      treasury: decoded.treasury.toBase58(),
      feeBps: decoded.feeBps,
      paused: decoded.paused,
    });
    return;
  }

  const treasury = new PublicKey(process.env.TREASURY ?? DEFAULT_TREASURY);
  const feeBps = Number(process.env.FEE_BPS ?? DEFAULT_FEE_BPS);

  const signature = await program.methods
    .initializeConfig(treasury, feeBps)
    .accounts({
      admin: provider.wallet.publicKey,
      config,
      systemProgram: anchor.web3.SystemProgram.programId,
    })
    .rpc();

  console.log("initialize_config:", signature, {
    admin: provider.wallet.publicKey.toBase58(),
    treasury: treasury.toBase58(),
    feeBps,
  });
};
