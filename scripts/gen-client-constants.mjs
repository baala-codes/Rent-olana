#!/usr/bin/env node
/**
 * Generate `clients/ts/generated.ts` from `clients/idl/asset_rental.json`.
 *
 * The IDL is the single source of the Anchor discriminators. Publishing them as
 * a typed module (instead of importing JSON) keeps the portal bundle small and
 * lets Node, Vite, and `tsc` consume it without JSON-module caveats.
 *
 * Usage:
 *   node scripts/gen-client-constants.mjs          # write the file
 *   node scripts/gen-client-constants.mjs --check  # fail if it is out of date
 */

import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = fileURLToPath(new URL("..", import.meta.url));
const IDL_PATH = join(ROOT, "clients/idl/asset_rental.json");
const OUT_PATH = join(ROOT, "clients/ts/generated.ts");

const hex = (bytes, kind, name) => {
  if (!Array.isArray(bytes) || bytes.length !== 8) {
    throw new Error(`IDL ${kind} "${name}" has no 8-byte discriminator`);
  }
  return bytes.map((byte) => byte.toString(16).padStart(2, "0")).join("");
};

const record = (entries) =>
  `{\n${entries
    .map(([name, value]) => `  ${JSON.stringify(name)}: "${value}",`)
    .join("\n")}\n}`;

const idl = JSON.parse(readFileSync(IDL_PATH, "utf8"));

if (!idl.address) throw new Error("IDL has no program address");

const instructions = [...idl.instructions]
  .map((ix) => [ix.name, hex(ix.discriminator, "instruction", ix.name)])
  .sort(([a], [b]) => a.localeCompare(b));

const accounts = [...idl.accounts]
  .map((account) => [account.name, hex(account.discriminator, "account", account.name)])
  .sort(([a], [b]) => a.localeCompare(b));

const source = `/**
 * @generated by scripts/gen-client-constants.mjs from
 * clients/idl/asset_rental.json. Do not edit by hand.
 *
 * Regenerate with \`bash scripts/export-clients.sh\` or \`npm run clients:gen\`.
 */

/** Program address published in the IDL. */
export const IDL_ADDRESS = "${idl.address}";

/** Instruction name -> 8-byte discriminator, as hex. */
export const IDL_INSTRUCTION_DISCRIMINATORS: Readonly<Record<string, string>> = ${record(instructions)};

/** Account name -> 8-byte discriminator, as hex. */
export const IDL_ACCOUNT_DISCRIMINATORS: Readonly<Record<string, string>> = ${record(accounts)};
`;

if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(OUT_PATH, "utf8");
  } catch {
    // Missing file is a mismatch.
  }
  if (current !== source) {
    console.error(
      "error: clients/ts/generated.ts is out of date with clients/idl/asset_rental.json.\n" +
        "       Run `node scripts/gen-client-constants.mjs` and commit the result."
    );
    process.exit(1);
  }
  console.log("generated client constants are up to date");
} else {
  writeFileSync(OUT_PATH, source);
  console.log(`wrote ${OUT_PATH} (${instructions.length} instructions, ${accounts.length} accounts)`);
}
