    assert.equal((await balance(renter.publicKey)) - renterBefore, rentMin);
    assert.equal(await connection.getAccountInfo(rental, "finalized"), null);

    await closeListing(program, { owner: ownerA.publicKey, listing, signers: [ownerA] });
