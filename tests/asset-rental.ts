/**
 * The cluster the suite is actually running against. `anchor test` exports
 * `ANCHOR_PROVIDER_URL` for the selected cluster, so derive the fixture label
 * from it rather than from the devnet-configured `CLUSTER` constant; otherwise
 * a localnet run would write fixtures that claim to be devnet.
 */
const clusterLabel = ((): string => {
  const url = process.env.ANCHOR_PROVIDER_URL ?? RPC_URL;
  if (/127\.0\.0\.1|localhost/.test(url)) return "localnet";
  if (url.includes("devnet")) return "devnet";
  if (url.includes("mainnet")) return "mainnet";
  return CLUSTER;
})();

const nowTs = (): number => Math.floor(Date.now() / 1000);

const waitFinalized = async (signature: TransactionSignature): Promise<void> => {
  const latest = await connection.getLatestBlockhash("finalized");
  await connection.confirmTransaction({ signature, ...latest }, "finalized");
};

const SYSVAR_CLOCK = new PublicKey("SysvarC1ock11111111111111111111111111111111");

/**
 * The local validator's `Clock` (not the wall clock) is the source of truth for
 * `start_ts`/`end_ts` gates. On a test validator the chain clock can lag wall
 * time, so "starts now" cases must anchor on it rather than on `Date.now()`.
 */
const chainNow = async (): Promise<number> => {
  // Anchor's preflight simulation runs against the connection's `finalized`
  // bank, so a program's `Clock::get()` is the finalized clock. Anchor start
  // times on the same clock, or a time-gated call fails even though the latest
  // processed slot is already past `start_ts`.
  const info = await connection.getAccountInfo(SYSVAR_CLOCK, "finalized");
  return Number(info!.data.readBigInt64LE(32));
};

/**
 * Poll until the processed chain clock is comfortably past `ts`.
 *
 * Anchor's preflight simulation runs against the connection's `finalized`
 * bank, so the `Clock::get()` a program sees can lag the latest processed
 * slot; START_EXTRA covers that lag before a time-gated call is attempted.
 */
const START_EXTRA = Number(process.env.START_EXTRA ?? 2);

/**
 * Book a rental that starts as soon as the validator allows.
 *
 * `create_rental` requires `start_ts >= Clock::get()`, and the transaction is
 * built *after* the timestamp is chosen, so a fixed lead can lose the race: a
 * short one reverts with `StartInPast`, and a long one makes every time-gated
 * case sit and wait. Instead, start with a small lead and, only if the program
 * actually returns `StartInPast`, retry with a fresh timestamp and a larger
 * lead. Retrying is safe: the failed `init` created no rental account and the
 * same `rental_id` is reused, so no second escrow can be taken.
 */
const BOOK_LEAD_SECONDS = Number(process.env.BOOK_LEAD_SECONDS ?? 5);

/**
 * Every rental created by the suite, keyed by address, with the wallet that
 * funded it. A rental account keeps its rent-exempt balance after it reaches a
 * terminal state, so a 0.05 SOL budget would be consumed by account rent alone
 * across the cases and the 20-iteration fuzz loop. `afterEach` closes terminal
 * rentals to return that rent to the renter before the next case starts.
 */
const trackedRentals = new Map<string, PublicKey>();

/** Wrap the client builder so every successfully created rental is tracked. */
async function createRental(
  ...args: Parameters<typeof createRentalOnChain>
): ReturnType<typeof createRentalOnChain> {
  const result = await createRentalOnChain(...args);
  trackedRentals.set(result.rental.toBase58(), args[1].renter);
  return result;
}

async function bookStartingSoon(
  listing: PublicKey,
  rentalId: Buffer,
  days: number
): Promise<{ signature: TransactionSignature; startTs: number }> {
  let lead = BOOK_LEAD_SECONDS;
  for (let attempt = 0; attempt < 4; attempt += 1) {
    const startTs = (await chainNow()) + lead;
    try {
      const { signature } = await createRental(program, {
        renter: renter.publicKey,
        listing,
        rentalId,
        startTs,
        days,
        signers: [renter],
      });
      return { signature, startTs };
    } catch (error) {
      if (programErrorCode(error) !== RENTAL_ERROR_CODE.StartInPast) throw error;
      console.warn(`  booking start_ts lost the clock race; retrying with lead=${lead * 2}s`);
      lead = Math.max(lead * 2, 10);
    }
  }
  throw new Error("could not book a rental that starts in the near future");
}

const waitForStart = async (ts: number): Promise<void> => {
  while ((await chainNow()) < ts + START_EXTRA) {
    await new Promise((resolve) => setTimeout(resolve, 400));
  }
};

const feeOf = async (signature: TransactionSignature): Promise<number> => {
  const tx = await connection.getTransaction(signature, {
    commitment: "finalized",
    maxSupportedTransactionVersion: 0,
  });
  return tx?.meta?.fee ?? 0;
};

const balance = (pubkey: PublicKey): Promise<number> =>
  connection.getBalance(pubkey, "finalized");

async function fund(to: PublicKey, sol = 0.05): Promise<void> {
  const tx = new anchor.web3.Transaction().add(
    SystemProgram.transfer({
      fromPubkey: admin.publicKey,
      toPubkey: to,
      lamports: sol * LAMPORTS_PER_SOL,
    })
  );
  await provider.sendAndConfirm(tx, [admin]);
}

type Snap = { address: string; exists: boolean; lamports: number };

async function snapshot(accounts: Record<string, PublicKey>): Promise<Record<string, Snap>> {
  const entries = Object.entries(accounts);
  const infos = await connection.getMultipleAccountsInfo(
    entries.map(([, pk]) => pk),
    "finalized"
  );
  const out: Record<string, Snap> = {};
  entries.forEach(([name, pk], i) => {
    out[name] = {
      address: pk.toBase58(),
      exists: infos[i] !== null,
      lamports: infos[i]?.lamports ?? 0,
    };
  });
  return out;
}

/** Run a case, capture a pre/post snapshot of `tracked`, and dump a fixture. */
async function scenario(
  name: string,
  tracked: Record<string, PublicKey>,
  fn: () => Promise<TransactionSignature | null>
): Promise<void> {
  const before = await snapshot(tracked);
  let signature: TransactionSignature | null = null;
  try {
    signature = await fn();
    if (signature) await waitFinalized(signature);
  } finally {
    const after = await snapshot(tracked);
    const accounts: Record<string, unknown> = {};
    for (const key of Object.keys(tracked)) {
      accounts[key] = {
        address: before[key].address,
        exists: after[key].exists,
        before: before[key],
        after: after[key],
      };
    }
    mkdirSync(FIXTURES, { recursive: true });
    writeFileSync(
      join(FIXTURES, `${name}.json`),
      JSON.stringify(
        {
          scenario: name,
          cluster: clusterLabel,
          programId: PROGRAM_ID.toBase58(),
          signature,
          accounts,
          capturedAt: new Date().toISOString(),
        },
        null,
        2
      ) + "\n"
    );
  }
}

/**
 * Recover the program error code from any failure shape.
 *
 * The old `e?.error?.errorCode?.number` path returned `undefined` for every
 * failed instruction because Anchor 0.30 + web3.js >= 1.95 mask the error as
 * `Unknown action 'undefined'` (the client re-simulates to recover the logs).
 */
const codeOf = (err: unknown): number | undefined => programErrorCode(err);

async function expectError(fn: () => Promise<unknown>, name: keyof typeof RENTAL_ERROR_CODE): Promise<void> {
  const expected = RENTAL_ERROR_CODE[name as string];
  try {
    await fn();
  } catch (err) {
    const code = codeOf(err);
    const failure = parseProgramError(err);
    const detail = failure.logs.length > 0 ? `\n${failure.logs.join("\n")}` : "";
    assert.equal(
      code,
      expected,
      `expected ${String(name)} (${expected}), got ${code ?? `<no code: ${failure.message}>`}${detail}`
    );
    return;
  }
  assert.fail(`expected ${String(name)}, but the call succeeded`);
}

async function expectFailure(fn: () => Promise<unknown>): Promise<void> {
  try {
    await fn();
  } catch {
    return;
  }
  assert.fail("expected the call to fail");
}

/**
 * Anchor 0.30 decodes the `RentalStatus` enum to `{ variantName: value }`
 * (e.g. `{ reserved: {} }`), not to the numeric discriminant. Map the decoded
 * value back to the published code so assertions can stay exact.
 */
const statusCode = (status: unknown): number => {
  if (typeof status === "number") return status;
  const key = Object.keys(status as Record<string, unknown>)[0];
  const pascal = key.charAt(0).toUpperCase() + key.slice(1);
  return (RENTAL_STATUS as Record<string, number>)[pascal];
};

/**
 * Reclaim rent from every terminal rental this case left behind. This runs after
 * the fixture snapshot is written, so fixtures still show the terminal account;
 * it only affects the wallet budget for the next case.
 */
afterEach(async () => {
  for (const [address, renterWallet] of trackedRentals) {
    const rental = new PublicKey(address);
    if (!(await connection.getAccountInfo(rental, "finalized"))) continue;

    const r = await program.account.rentalAgreement.fetch(rental);
    const code = statusCode(r.status);
    const terminal =
      code === RENTAL_STATUS.Completed ||
      code === RENTAL_STATUS.Cancelled ||
      code === RENTAL_STATUS.Resolved;
    if (!terminal) continue;

    await closeRental(program, { rental, renterWallet });
  }
  trackedRentals.clear();
});

